#!/usr/bin/env node
/**
 * Generates harness/perf-personas.js from the REAL ext/src/personas.js.
 *
 * harness/performance.html has to hand the shim a persona synchronously, at
 * document_start, before anything else runs — so the persona cannot be fetched.
 * Transcribing it by hand is how a harness ends up measuring a persona the
 * shipped pool does not contain, so it is generated instead.
 *
 *   node harness/gen-perf-personas.mjs
 *
 * Re-run whenever ext/src/personas.js changes. performance.html asserts the
 * persona id is in the shim's own inlined pool, so drift fails loudly rather
 * than producing a quiet wrong number.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { personaFor } from '../ext/src/personas.js';

const here = dirname(fileURLToPath(import.meta.url));

// One salt per OS family, same salts harness/shim-test.html uses so the two
// harnesses talk about the same machines.
//   mac   — the ONLY family the real extension can hand a Mac host (D12).
//   linux — 180 font families since the 2026-09-16 ground-truth work; the
//           font-cost question in docs/PERFORMANCE is specifically about it.
//   win   — 57 families, kept as a middle data point.
const WANT = [
  ['nullecho-shim-test-0003', 'mac'],
  ['nullecho-shim-test-0005', 'linux'],
  ['nullecho-shim-test-0001', 'win'],
];

const out = {};
for (const [salt, family] of WANT) out[salt] = personaFor(salt, 'localhost', family);

const body = `// GENERATED by harness/gen-perf-personas.mjs from ext/src/personas.js — do not edit.
// Generated ${new Date().toISOString().slice(0, 10)}.
window.__PERF_PERSONAS = ${JSON.stringify(out, null, 0)};
window.__PERF_PERSONA_FAMILIES = ${JSON.stringify(Object.fromEntries(WANT.map(([s, f]) => [s, f])))};
`;

writeFileSync(join(here, 'perf-personas.js'), body);
for (const [salt] of WANT) {
  const p = out[salt];
  process.stderr.write(`${salt} → ${p.id} (${(p.fontList || []).length} fonts)\n`);
}
process.stderr.write(`wrote ${join(here, 'perf-personas.js')}\n`);
